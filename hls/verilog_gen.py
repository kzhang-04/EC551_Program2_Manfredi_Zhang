"""Write the synthesized design as Verilog.

Three modules come out, all regenerated on every compile:

* ``hls_datapath``: input registers, functional units, muxes, working
  registers and the observability mux.
* ``hls_controller``: the FSM. State k runs schedule step k and drives the
  mux selects and register write-enables for that step.
* ``hls_core``: wraps both behind a port list that is the same for every
  design, so the board top level never changes.

Registers and the FSM only change on clock edges where ``en`` is high. On
the board, ``en`` is one debounced press of the step button.
"""

from hls import DATA_WIDTH
from hls.dag import UNIT_NAME
from hls.design import LED_FUS, Design

W = DATA_WIDTH
VIEW_FU, VIEW_OUTPUT, VIEW_REG, VIEW_INPUT = range(4)


def _header(d: Design, what: str) -> list[str]:
    return [
        f"// {what}",
        f"// Generated by the EC551 HLS tool from {d.source} ({d.sched.mode} schedule,",
        f"// {d.sched.latency} steps). Do not edit: rerun the tool instead.",
    ]


def _vec(width: int) -> str:
    return "" if width == 1 else f"[{width - 1}:0] "


def _mux(out: str, sel: str, options: list[tuple[str, str]], indent: str = "    ") -> list[str]:
    """Combinational mux as a case statement. ``options`` are (expr, comment)."""
    width = max(1, (len(options) - 1).bit_length())
    lines = [f"{indent}always @* begin", f"{indent}    case ({sel})"]
    for i, (expr, comment) in enumerate(options):
        lines.append(f"{indent}        {width}'d{i}: {out} = {expr};" + (f"  // {comment}" if comment else ""))
    lines += [f"{indent}        default: {out} = {{{W}{{1'b0}}}};",
              f"{indent}    endcase", f"{indent}end"]
    return lines


def _port_list(ports: list[str]) -> list[str]:
    return [f"    {p}," for p in ports[:-1]] + [f"    {ports[-1]}"]


def debug_items(d: Design) -> list[list[tuple[str, str]]]:
    """What each view shows, as (signal, label) lists indexed by dbg_sel."""
    b = d.binding
    fus = [(f"{fu.name}_y", f"{fu.name} ({UNIT_NAME[fu.kind]} {fu.index})") for fu in b.fus]
    outputs = [(b.regs[d.output_reg(i)].name, f"{v.base} ({v})")
               for i, v in enumerate(d.program.outputs)]
    regs = [(r.name, ", ".join(str(d.dag.nodes[v].dest) for v in r.values)) for r in b.regs]
    inputs = [(f"in_{v.base}", v.base) for v in b.inputs]
    return [fus, outputs, regs, inputs]


def generate_datapath(d: Design) -> str:
    b = d.binding
    lines = _header(d, "Datapath: input registers, functional units, muxes and registers.")
    ports = ["input  wire clk", "input  wire rst", "input  wire en",
             "input  wire in_we", "input  wire [5:0] in_sel", f"input  wire [{W - 1}:0] in_data"]
    ports += [f"input  wire {_vec(s.width)}{s.name}" for s in d.signals]
    ports += ["input  wire [1:0] view", "input  wire [5:0] dbg_sel",
              f"output reg  [{W - 1}:0] dbg_value"]
    lines += ["module hls_datapath ("] + _port_list(ports) + [");", ""]

    # Input registers
    lines.append("    // Input registers, loaded one at a time from the switches.")
    if b.inputs:
        lines.append(f"    reg [{W - 1}:0] " + ", ".join(f"in_{v.base}" for v in b.inputs) + ";")
        lines += ["    always @(posedge clk) begin", "        if (rst) begin"]
        lines += [f"            in_{v.base} <= {W}'d0;" for v in b.inputs]
        lines += ["        end else if (in_we) begin", "            case (in_sel)"]
        lines += [f"                6'd{i}: in_{v.base} <= in_data;" for i, v in enumerate(b.inputs)]
        lines += ["                default: ;", "            endcase", "        end", "    end"]
    else:
        lines.append("    // (none: every input is hardcoded)")
    lines.append("")

    # Working registers
    lines.append("    // Working registers. Values with non-overlapping lifetimes share one.")
    for r in b.regs:
        held = ", ".join(str(d.dag.nodes[v].dest) for v in r.values)
        lines.append(f"    reg [{W - 1}:0] {r.name};  // {held}")
    lines.append("")

    # Functional units and their input muxes
    lines.append("    // Functional units and their input muxes.")
    for fi, fu in enumerate(b.fus):
        ops = [n for n in d.dag.nodes if b.op_fu[n.id] == fi]
        lines.append(f"    // {fu.name}: " + "; ".join(
            f"step {d.sched.steps[n.id]} {n}" for n in sorted(ops, key=lambda n: d.sched.steps[n.id])))
        for port, sources in (("a", fu.a_sources), ("b", fu.b_sources)):
            signal = f"{fu.name}_{port}"
            if len(sources) == 1:
                lines.append(f"    wire [{W - 1}:0] {signal} = {sources[0].name};")
            else:
                lines.append(f"    reg  [{W - 1}:0] {signal};")
                lines += _mux(signal, f"{signal}_sel", [(s.name, "") for s in sources])
        lines.append(f"    wire [{W - 1}:0] {fu.name}_y;")
        lines.append(f"    {UNIT_NAME[fu.kind]} #(.WIDTH({W})) u_{fu.name} "
                     f"(.a({fu.name}_a), .b({fu.name}_b), .y({fu.name}_y));")
        lines.append("")

    # Register input muxes and updates
    lines.append("    // Register input muxes.")
    for r in b.regs:
        writers = [b.fus[fi].name for fi in r.writers]
        if len(writers) == 1:
            lines.append(f"    wire [{W - 1}:0] {r.name}_d = {writers[0]}_y;")
        else:
            lines.append(f"    reg  [{W - 1}:0] {r.name}_d;")
            lines += _mux(f"{r.name}_d", f"{r.name}_sel", [(f"{w}_y", "") for w in writers])
    lines += ["", "    // A register only changes on an enabled edge with its write-enable set.",
              "    always @(posedge clk) begin", "        if (rst) begin"]
    lines += [f"            {r.name} <= {W}'d0;" for r in b.regs]
    lines += ["        end else if (en) begin"]
    lines += [f"            if ({r.name}_we) {r.name} <= {r.name}_d;" for r in b.regs]
    lines += ["        end", "    end", ""]

    # Observability mux
    lines += ["    // Observability: view picks the category, dbg_sel the item.",
              "    always @* begin", f"        dbg_value = {W}'d0;", "        case (view)"]
    names = ["functional unit outputs", "outputs", "registers", "inputs"]
    for view, items in enumerate(debug_items(d)):
        lines.append(f"            2'd{view}: begin  // {names[view]}")
        if items:
            lines.append("                case (dbg_sel)")
            lines += [f"                    6'd{i}: dbg_value = {sig};  // {label}"
                      for i, (sig, label) in enumerate(items)]
            lines += ["                    default: ;", "                endcase"]
        lines.append("            end")
    lines += ["        endcase", "    end", "endmodule", ""]
    return "\n".join(lines)


def generate_controller(d: Design) -> str:
    lines = _header(d, "Controller: one FSM state per schedule step.")
    ports = ["input  wire clk", "input  wire rst", "input  wire en", "input  wire start",
             "input  wire restart", "output reg  [7:0] state", "output wire done",
             f"output reg  [{LED_FUS - 1}:0] fu_active"]
    ports += [f"output reg  {_vec(s.width)}{s.name}" for s in d.signals]
    lines += ["module hls_controller ("] + _port_list(ports) + [");", ""]
    lines += [
        "    localparam IDLE = 8'd0;",
        f"    localparam DONE = 8'd{d.done_state};",
        "",
        "    assign done = (state == DONE);",
        "",
        "    // IDLE -> step 1 -> ... -> last step -> DONE, one state per enabled edge.",
        "    always @(posedge clk) begin",
        "        if (rst || restart)",
        "            state <= IDLE;",
        "        else if (en) begin",
        "            case (state)",
        "                IDLE: if (start) state <= 8'd1;",
        "                DONE: state <= DONE;",
        "                default: state <= state + 8'd1;",
        "            endcase",
        "        end",
        "    end",
        "",
        "    // Control signals for each state. Anything not set here is 0.",
        "    always @* begin",
        f"        fu_active = {LED_FUS}'d0;",
    ]
    lines += [f"        {s.name} = {s.width}'d0;" for s in d.signals]
    lines.append("        case (state)")
    for st in d.states:
        lines.append(f"            8'd{st.step}: begin")
        lines += [f"                // {note}" for note in st.notes] or ["                // (idle)"]
        for name, value in st.values.items():
            width = next(s.width for s in d.signals if s.name == name)
            lines.append(f"                {name} = {width}'d{value};")
        mask = sum(1 << i for i in st.active if i < LED_FUS)
        lines.append(f"                fu_active = {LED_FUS}'b{mask:0{LED_FUS}b};")
        lines.append("            end")
    lines += ["            default: ;", "        endcase", "    end", "endmodule", ""]
    return "\n".join(lines)


def generate_core(d: Design) -> str:
    lines = _header(d, "Synthesized core: datapath plus controller behind a fixed port list.")
    lines += [
        "module hls_core (",
        "    input  wire clk,",
        "    input  wire rst,",
        "    input  wire en,          // one enabled edge = one step",
        "    input  wire start,       // leave IDLE on the next enabled edge",
        "    input  wire restart,     // back to IDLE, keeping the inputs",
        "    input  wire in_we,       // load in_data into input number in_sel",
        "    input  wire [5:0] in_sel,",
        f"    input  wire [{W - 1}:0] in_data,",
        "    input  wire [1:0] view,  // 0 FU outputs, 1 outputs, 2 registers, 3 inputs",
        "    input  wire [5:0] dbg_sel,",
        f"    output wire [{W - 1}:0] dbg_value,",
        f"    output wire [{LED_FUS - 1}:0] fu_active,",
        "    output wire [7:0] state,",
        "    output wire done",
        ");",
    ]
    lines += [f"    wire {_vec(s.width)}{s.name};" for s in d.signals]
    connections = [f".{s.name}({s.name})" for s in d.signals]
    lines += [
        "",
        "    hls_controller u_ctrl (",
        "        .clk(clk), .rst(rst), .en(en), .start(start), .restart(restart),",
        "        .state(state), .done(done), .fu_active(fu_active),",
        "        " + ", ".join(connections),
        "    );",
        "",
        "    hls_datapath u_dp (",
        "        .clk(clk), .rst(rst), .en(en),",
        "        .in_we(in_we), .in_sel(in_sel), .in_data(in_data),",
        "        " + ", ".join(connections) + ",",
        "        .view(view), .dbg_sel(dbg_sel), .dbg_value(dbg_value)",
        "    );",
        "endmodule",
        "",
    ]
    return "\n".join(lines)
