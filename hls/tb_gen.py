"""Write a self-checking testbench for a generated hls_core.

For each test vector the testbench works like a person at the board:

1. Load every input through the in_we port.
2. Step once to leave IDLE.
3. In each state, check the state number, the busy-unit LEDs and every busy
   FU's output through the observability port.
4. Step, then check every register that was just written.
5. At DONE, check every output.

Expected values come from the Python reference model (golden.py), so the
hardware is checked against the equations, not against itself.
"""

from hls import DATA_WIDTH
from hls.design import LED_FUS, Design
from hls.golden import evaluate
from hls.verilog_gen import VIEW_FU, VIEW_INPUT, VIEW_OUTPUT, VIEW_REG

W = DATA_WIDTH


def _vector_text(vector: dict[str, int]) -> str:
    return " ".join(f"{k}={v}" for k, v in vector.items()) or "(no inputs)"


def generate_testbench(d: Design, vectors: list[dict[str, int]]) -> str:
    b = d.binding
    lines = [
        "`timescale 1ns/1ps",
        f"// Self-checking testbench for the design generated from {d.source}",
        f"// ({d.sched.mode} schedule). Generated by the EC551 HLS tool; do not edit.",
        "// Prints one FAIL line per mismatch, then a PASS or FAIL summary.",
        "module testbench;",
        "    reg clk = 1'b0;",
        "    reg rst = 1'b1, en = 1'b0, start = 1'b1, restart = 1'b0;",
        "    reg in_we = 1'b0;",
        "    reg [5:0] in_sel = 6'd0;",
        f"    reg [{W - 1}:0] in_data = {W}'d0;",
        "    reg [1:0] view = 2'd0;",
        "    reg [5:0] dbg_sel = 6'd0;",
        f"    wire [{W - 1}:0] dbg_value;",
        f"    wire [{LED_FUS - 1}:0] fu_active;",
        "    wire [7:0] state;",
        "    wire done;",
        "    integer errors = 0, checks = 0;",
        "",
        "    hls_core dut (",
        "        .clk(clk), .rst(rst), .en(en), .start(start), .restart(restart),",
        "        .in_we(in_we), .in_sel(in_sel), .in_data(in_data),",
        "        .view(view), .dbg_sel(dbg_sel), .dbg_value(dbg_value),",
        "        .fu_active(fu_active), .state(state), .done(done)",
        "    );",
        "",
        "    always #5 clk = ~clk;",
        "",
        "    // Signals change on the falling edge, so they're stable at the rising edge.",
        f"    task load(input [5:0] index, input [{W - 1}:0] value);",
        "        begin",
        "            @(negedge clk); in_sel = index; in_data = value; in_we = 1'b1;",
        "            @(negedge clk); in_we = 1'b0;",
        "        end",
        "    endtask",
        "",
        "    // Exactly one enabled rising edge, like one press of the step button.",
        "    task step;",
        "        begin",
        "            @(negedge clk); en = 1'b1;",
        "            @(negedge clk); en = 1'b0;",
        "        end",
        "    endtask",
        "",
        f"    task check(input [1:0] v, input [5:0] index, input [{W - 1}:0] want,",
        "               input [8*64-1:0] what);",
        "        begin",
        "            view = v; dbg_sel = index; #1;",
        "            checks = checks + 1;",
        "            if (dbg_value !== want) begin",
        "                errors = errors + 1;",
        '                $display("FAIL %0s: got %0d, want %0d", what, dbg_value, want);',
        "            end",
        "        end",
        "    endtask",
        "",
        f"    task check_state(input [7:0] want_state, input [{LED_FUS - 1}:0] want_active);",
        "        begin",
        "            checks = checks + 1;",
        f"            if (state !== want_state || fu_active !== want_active",
        f"                    || done !== (want_state == 8'd{d.done_state})) begin",
        "                errors = errors + 1;",
        '                $display("FAIL state: got %0d (busy %b, done %b), want %0d (busy %b)",',
        "                         state, fu_active, done, want_state, want_active);",
        "            end",
        "        end",
        "    endtask",
        "",
        "    initial begin",
        "        repeat (2) @(negedge clk);",
        "        rst = 1'b0;",
    ]

    producer_reg = b.value_reg
    for k, vector in enumerate(vectors, start=1):
        values, _ = evaluate(d.program, vector)
        outs = " ".join(f"{v.base}={values[v]}" for v in d.program.outputs)
        lines += ["", f"        // vector {k}: {_vector_text(vector)}  ->  {outs}",
                  f'        $display("vector {k}: {_vector_text(vector)} -> expect {outs}");',
                  "        @(negedge clk); restart = 1'b1;",
                  "        @(negedge clk); restart = 1'b0;"]
        for i, v in enumerate(b.inputs):
            lines.append(f"        load(6'd{i}, {W}'d{vector[v.base]});")
        for i, v in enumerate(b.inputs):
            lines.append(f'        check(2\'d{VIEW_INPUT}, 6\'d{i}, {W}\'d{vector[v.base]}, "input {v.base}");')
        lines += [f"        check_state(8'd0, {LED_FUS}'d0);", "        step;"]
        for st in d.states:
            mask = sum(1 << i for i in st.active if i < LED_FUS)
            lines.append(f"        check_state(8'd{st.step}, {LED_FUS}'b{mask:0{LED_FUS}b});")
            nodes = d.sched.nodes_in_step(d.dag, st.step)
            for n in nodes:
                fi = b.op_fu[n.id]
                lines.append(f"        check(2'd{VIEW_FU}, 6'd{fi}, {W}'d{values[n.dest]}, "
                             f'"step {st.step} {b.fus[fi].name} = {n.dest}");')
            lines.append("        step;")
            for n in nodes:
                r = producer_reg[n.id]
                lines.append(f"        check(2'd{VIEW_REG}, 6'd{r}, {W}'d{values[n.dest]}, "
                             f'"after step {st.step} r{r} = {n.dest}");')
        lines.append(f"        check_state(8'd{d.done_state}, {LED_FUS}'d0);")
        for i, v in enumerate(d.program.outputs):
            lines.append(f"        check(2'd{VIEW_OUTPUT}, 6'd{i}, {W}'d{values[v]}, "
                         f'"output {v.base}");')

    lines += [
        "",
        "        if (errors == 0)",
        f'            $display("PASS: {len(vectors)} vectors, %0d checks", checks);',
        "        else",
        '            $display("FAIL: %0d of %0d checks failed", errors, checks);',
        "        $finish;",
        "    end",
        "endmodule",
        "",
    ]
    return "\n".join(lines)
